/**
 * Придержка места при перевёрстке.
 *
 * Вёрстка ленивая: высота абзацев, до которых читатель не дошёл, сперва
 * угадана, а потом, когда до них доходит очередь, уточняется. Всё, что ниже
 * уточнённого, съезжает — а если уточнили выше места чтения, съезжает и само
 * место. Измерено: прыжок на трёхтысячный абзац, и за две секунды он уполз на
 * 1245 пикселей.
 *
 * Chromium этого не показывает: он придерживает содержимое сам (scroll
 * anchoring), и снос выходит 0.125 пикселя. В Safari — а телефон читателя как
 * раз на нём — придержки нет вовсе. Поэтому придерживаем сами.
 *
 * Здесь — только решение: поправлять ли, ждать ли ещё и когда перестать.
 * Измерения и прокрутка остаются в `main.ts`; решение же проверяется без
 * браузера, а цена ошибки в нём — потерянное место в книге.
 */

/** Меньше пикселя — это не «уехал», а округление. */
export const STEADY_PX = 1;

/**
 * Сколько кадров подряд без поправки считать, что высоты устоялись.
 *
 * Одного мало: уточнения приходят не каждый кадр, и на первой же паузе
 * придержка решила бы, что всё кончилось, — а книга поехала бы дальше.
 */
export const STEADY_FRAMES = 5;

/**
 * Дольше этого не держим.
 *
 * Придержка возвращает читателя туда, откуда он смотрел, и это хорошо ровно
 * до тех пор, пока он сам никуда не собрался. Если высоты почему-то не
 * устоялись вовсе, вечно тянуть страницу назад — худшее, что можно сделать.
 */
export const HOLD_MS = 2000;

/** Что делать с этим кадром. */
export type Step = "поправить" | "ждать" | "хватит";

export interface Holder {
  /** Абзац уехал на столько пикселей. Что делать? */
  step(drift: number, now: number): Step;
  /** Читатель тронул прокрутку сам: спорить с ним нельзя. */
  release(): void;
}

/**
 * Придержка, начатая в этот миг.
 *
 * `now` передаётся снаружи, а не берётся из часов: так придержку можно
 * прокрутить в проверке по кадрам, не ожидая двух секунд по-настоящему.
 */
export function holdPlace(startedAt: number): Holder {
  let quiet = 0;
  let released = false;

  return {
    step(drift: number, now: number): Step {
      if (released) return "хватит";
      if (now - startedAt >= HOLD_MS) return "хватит";
      if (Math.abs(drift) > STEADY_PX) {
        // Уехал — счёт спокойных кадров начинается заново: уточнения высот
        // идут волнами, и одна тишина посреди волны ничего не значит.
        quiet = 0;
        return "поправить";
      }
      quiet += 1;
      return quiet >= STEADY_FRAMES ? "хватит" : "ждать";
    },
    release(): void {
      released = true;
    },
  };
}

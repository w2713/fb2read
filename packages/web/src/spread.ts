/**
 * Разворот: арифметика двух колонок.
 *
 * Ни DOM, ни браузера здесь нет — только числа, поэтому всё проверяется без
 * экрана. А проверять есть что: каждое из этих правил в опытах оказалось не
 * тем, чем выглядело.
 *
 * Почему разворот вообще листается, а не прокручивается. Многоколонник CSS
 * ведёт текст до низа первой колонки и продолжает в следующей — то есть при
 * прокрутке вниз читателю пришлось бы возвращаться наверх за каждой второй
 * колонкой. Две колонки в браузере неизбежно означают страницы, как разворот в
 * терминале.
 */

/** Уже этого вторая колонка не имеет смысла, в рем. */
export const MIN_COLUMN = 24;

/** Промежуток между колонками — «корешок» разворота, в рем. */
export const GUTTER = 3;

/**
 * Ниже этого разворот не имеет смысла, в рем.
 *
 * Порог по высоте нужен не для красоты, а из-за телефона: iPhone в альбомной
 * ориентации даёт окно 844×390, и по ширине он проходит с запасом. Колонка в
 * нём вышла бы в пять строк — читать такое нельзя. Мерить надо оба измерения.
 */
export const MIN_HEIGHT = 30;

/**
 * Пускает ли окно разворот.
 *
 * Размеры в пикселях, `rem` — размер корневого шрифта: читатель мог увеличить
 * его средствами системы, и тогда в те же пиксели помещается меньше текста.
 */
export function fitsSpread(width: number, height: number, rem: number): boolean {
  return width >= (MIN_COLUMN * 2 + GUTTER) * rem && height >= MIN_HEIGHT * rem;
}

/**
 * Шаг страницы — на сколько пикселей уезжает книга при листании.
 *
 * Не ширина окна, и это главная ловушка разворота. Колонки лежат с промежутком
 * между ними, и следующий разворот начинается за промежутком: при ширине
 * содержимого 1248 и промежутке 48 разворот занимает 1296, а не 1248. Листание
 * по ширине окна уползало бы на промежуток каждую страницу — измерено.
 *
 * Промежутков между двумя колонками один, а между разворотами — ещё один,
 * поэтому шаг одинаков при любом числе колонок: содержимое плюс промежуток.
 */
export function pageStep(content: number, gap: number): number {
  return Math.max(content + gap, 1);
}

/**
 * Допуск при переводе смещения в номер страницы, в пикселях.
 *
 * Ширины колонок дробные, и начало страницы приходится не на целое число.
 * Без допуска смещение, на волос не дотянувшее до границы, считалось бы
 * предыдущей страницей — то есть переход к абзацу оставлял бы его за краем.
 */
const ДОПУСК = 1;

/** На какой странице лежит это смещение. */
export function pageAt(offset: number, step: number): number {
  return Math.max(Math.floor((offset + ДОПУСК) / step), 0);
}

/** Где начинается эта страница. */
export function pageLeft(page: number, step: number): number {
  return page * step;
}

/**
 * Сколько всего страниц.
 *
 * Хотя бы одна: пустую книгу читалка не открывает, но и делить на ноль страниц
 * потом никому не придётся.
 */
export function pageCount(total: number, step: number): number {
  return Math.max(Math.ceil(total / step), 1);
}

/** Следующая страница в нужную сторону, за края книги не уходя. */
export function stepPage(page: number, delta: number, count: number): number {
  return Math.min(Math.max(page + delta, 0), count - 1);
}

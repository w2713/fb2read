/**
 * Оглавление деревом.
 *
 * Ядро отдаёт оглавление плоским списком, где у каждой строки записан уровень,
 * — так его хранит и эталонная реализация, и так его рисует терминал, отступом
 * в два пробела. В браузере от плоского списка мало толку: у книги с частями и
 * главами он выходит в сотни строк, и нужную главу в нём ищут прокруткой.
 *
 * Здесь только числа и порядок, без DOM, поэтому дерево проверяется обычными
 * проверками, а браузеру остаётся его нарисовать.
 */

import type { TocEntry } from "@fb2read/core";

/** Узел дерева: строка оглавления и то, что лежит под ней. */
export interface TocNode {
  entry: TocEntry;
  children: TocNode[];
}

/**
 * Собирает дерево из плоского списка с уровнями.
 *
 * Уровни в книгах приходят какие угодно, и дерево не должно от этого
 * разваливаться. Оглавление может начинаться не с нуля — тогда его первый
 * уровень и есть корневой. Уровень может перепрыгнуть через ступень (0, потом
 * сразу 2) — промежуточный узел не выдумывается, глубокая строка просто
 * ложится под ближайшую строку выше себя. И может опуститься ниже того, с чего
 * начиналось, — такая строка становится ещё одним корнем.
 *
 * Порядок строк сохраняется: он идёт по книге, и переставлять его нельзя.
 */
export function nestToc(entries: readonly TocEntry[]): TocNode[] {
  const roots: TocNode[] = [];
  /** Путь от корня к последнему добавленному узлу. */
  const path: TocNode[] = [];
  for (const entry of entries) {
    const node: TocNode = { entry, children: [] };
    // Снимаем с пути всех, кто не мельче: родителем может быть только строка
    // строго меньшего уровня.
    while (path.length && path[path.length - 1]!.entry.level >= entry.level) path.pop();
    if (path.length) path[path.length - 1]!.children.push(node);
    else roots.push(node);
    path.push(node);
  }
  return roots;
}

/**
 * Какая строка оглавления охватывает это место в книге.
 *
 * Та, что начинается не позже читаемого абзаца и позже всех прочих таких. Если
 * книга начинается до первой строки оглавления — предисловием, посвящением, —
 * ответа нет вовсе, и это честнее, чем указать на первую главу, которая ещё не
 * началась.
 *
 * Порядок строк не предполагается: оглавление EPUB пересобирается из nav или
 * ncx и приходит отсортированным по абзацу, но полагаться на это здесь незачем.
 */
export function entryAt(entries: readonly TocEntry[], block: number): number {
  let best = -1;
  for (let i = 0; i < entries.length; i += 1) {
    const at = entries[i]!.block;
    if (at > block) continue;
    if (best < 0 || at > entries[best]!.block) best = i;
  }
  return best;
}

/**
 * Есть ли в оглавлении вложенность.
 *
 * У книги с плоским оглавлением сворачивать нечего, и показывать треугольники
 * там незачем: в большинстве книг оглавление — это просто список глав.
 */
export function hasDepth(entries: readonly TocEntry[]): boolean {
  if (!entries.length) return false;
  const first = entries[0]!.level;
  return entries.some((entry) => entry.level !== first);
}

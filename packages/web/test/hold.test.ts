/**
 * Придержка места: когда поправлять, когда ждать и когда перестать.
 *
 * Эту часть можно проверить без браузера, и проверить надо обязательно:
 * ошибка здесь — либо потерянное место в книге, либо читалка, которая тянет
 * страницу назад, когда читатель уже листает сам.
 */

import { describe, expect, it } from "vitest";
import { HOLD_MS, STEADY_FRAMES, STEADY_PX, holdPlace } from "../src/hold.js";

/** Кадры идут по шестьдесят в секунду — как в браузере. */
const КАДР = 1000 / 60;

describe("придержка места", () => {
  it("уехавший абзац возвращают", () => {
    const держит = holdPlace(0);
    expect(держит.step(120, КАДР)).toBe("поправить");
  });

  it("возвращают и вверх, и вниз", () => {
    // Уточнение высоты выше места чтения уносит вперёд, ниже — назад.
    const держит = holdPlace(0);
    expect(держит.step(-120, КАДР)).toBe("поправить");
  });

  it("дрожь в полпикселя за отъезд не считают", () => {
    // Иначе придержка дёргала бы страницу на округлениях без конца.
    const держит = holdPlace(0);
    expect(держит.step(STEADY_PX / 2, КАДР)).toBe("ждать");
  });

  it("держат, пока высоты не устоятся, а не один кадр", () => {
    // Уточнения идут волнами: после первой тишины книга едет дальше.
    const держит = holdPlace(0);
    let время = КАДР;
    for (let i = 0; i < STEADY_FRAMES - 1; i += 1) {
      expect(держит.step(0, время)).toBe("ждать");
      время += КАДР;
    }
    expect(держит.step(0, время)).toBe("хватит");
  });

  it("тишина посреди волны счёт не заканчивает", () => {
    const держит = holdPlace(0);
    let время = КАДР;
    for (let i = 0; i < STEADY_FRAMES - 1; i += 1) {
      держит.step(0, время);
      время += КАДР;
    }
    // Книга поехала снова — значит, считать спокойные кадры надо заново.
    expect(держит.step(200, время)).toBe("поправить");
    время += КАДР;
    expect(держит.step(0, время)).toBe("ждать");
  });

  it("вечно не держат", () => {
    // Если высоты не устоялись вовсе, тянуть страницу назад без конца — худшее
    // из возможного: читатель не сможет уйти с места.
    const держит = holdPlace(1000);
    expect(держит.step(500, 1000 + HOLD_MS - КАДР)).toBe("поправить");
    expect(держит.step(500, 1000 + HOLD_MS)).toBe("хватит");
  });

  it("читатель тронул прокрутку — придержка уступает немедленно", () => {
    const держит = holdPlace(0);
    expect(держит.step(500, КАДР)).toBe("поправить");
    держит.release();
    expect(держит.step(500, 2 * КАДР)).toBe("хватит");
  });

  it("уступив однажды, обратно не берётся", () => {
    const держит = holdPlace(0);
    держит.release();
    держит.step(0, КАДР);
    expect(держит.step(500, 2 * КАДР)).toBe("хватит");
  });
});

/**
 * Оглавление деревом.
 *
 * Уровни в книгах приходят какие угодно: перепрыгивают ступень, начинаются не
 * с нуля, опускаются ниже начала. Дерево не должно от этого разваливаться, а
 * порядок строк — меняться: он идёт по книге.
 */

import type { TocEntry } from "@fb2read/core";
import { describe, expect, it } from "vitest";
import { entryAt, hasDepth, nestToc } from "../src/toc.js";

/** Короткая запись строки оглавления: уровень, название, абзац. */
function toc(...rows: Array<[number, string, number]>): TocEntry[] {
  return rows.map(([level, title, block]) => ({ level, title, block }));
}

/** Дерево в виде «название(дети)» — так его легче читать в проверке. */
function shape(nodes: ReturnType<typeof nestToc>): string {
  return nodes
    .map((node) => node.entry.title + (node.children.length ? `(${shape(node.children)})` : ""))
    .join(" ");
}

describe("дерево оглавления", () => {
  it("главы ложатся под свою часть", () => {
    const дерево = nestToc(
      toc([0, "Часть I", 0], [1, "Глава 1", 5], [1, "Глава 2", 40], [0, "Часть II", 90]),
    );
    expect(shape(дерево)).toBe("Часть I(Глава 1 Глава 2) Часть II");
  });

  it("плоское оглавление остаётся плоским", () => {
    const дерево = nestToc(toc([0, "Первая", 0], [0, "Вторая", 10], [0, "Третья", 20]));
    expect(shape(дерево)).toBe("Первая Вторая Третья");
    expect(дерево.every((node) => node.children.length === 0)).toBe(true);
  });

  it("перепрыгнутая ступень не выдумывает промежуточный узел", () => {
    // В книгах это бывает: часть, а под ней сразу подраздел третьего уровня.
    const дерево = nestToc(toc([0, "Часть", 0], [2, "Подраздел", 3], [2, "Ещё один", 8]));
    expect(shape(дерево)).toBe("Часть(Подраздел Ещё один)");
  });

  it("оглавление, начатое не с нуля, всё равно имеет корни", () => {
    // EPUB из nav сплошь и рядом отдаёт первый уровень единицей.
    const дерево = nestToc(toc([1, "Глава 1", 0], [2, "Раздел", 4], [1, "Глава 2", 20]));
    expect(shape(дерево)).toBe("Глава 1(Раздел) Глава 2");
  });

  it("строка ниже начального уровня становится ещё одним корнем", () => {
    const дерево = nestToc(toc([1, "Глава", 0], [2, "Раздел", 4], [0, "Приложение", 60]));
    expect(shape(дерево)).toBe("Глава(Раздел) Приложение");
  });

  it("порядок строк тот же, что в книге", () => {
    // Дерево — это способ показать, а не переставить: строки идут по книге.
    const дерево = nestToc(toc([0, "Б", 10], [0, "А", 20], [0, "В", 30]));
    expect(shape(дерево)).toBe("Б А В");
  });

  it("пустое оглавление не ломает сборку", () => {
    expect(nestToc([])).toEqual([]);
  });
});

describe("где читают сейчас", () => {
  const оглавление = toc([0, "Часть I", 10], [1, "Глава 1", 12], [1, "Глава 2", 40], [0, "Часть II", 90]);

  it("указывает на строку, которая началась и ещё не сменилась", () => {
    expect(entryAt(оглавление, 41)).toBe(2);
    expect(entryAt(оглавление, 89)).toBe(2);
    expect(entryAt(оглавление, 90)).toBe(3);
  });

  it("начало главы — уже эта глава, а не прошлая", () => {
    expect(entryAt(оглавление, 12)).toBe(1);
  });

  it("до первой строки ответа нет", () => {
    // Предисловие или посвящение идут раньше первой главы, и указывать на
    // главу, которая ещё не началась, было бы неправдой.
    expect(entryAt(оглавление, 0)).toBe(-1);
    expect(entryAt([], 5)).toBe(-1);
  });

  it("несортированное оглавление не сбивает ответ", () => {
    const вразброс = toc([0, "Третья", 30], [0, "Первая", 0], [0, "Вторая", 15]);
    expect(вразброс[entryAt(вразброс, 20)!]!.title).toBe("Вторая");
  });
});

describe("есть ли что сворачивать", () => {
  it("у плоского оглавления вложенности нет", () => {
    expect(hasDepth(toc([0, "Первая", 0], [0, "Вторая", 10]))).toBe(false);
    // И у книги, где все строки одного уровня, но не нулевого, — тоже нет.
    expect(hasDepth(toc([1, "Первая", 0], [1, "Вторая", 10]))).toBe(false);
  });

  it("разные уровни — это вложенность", () => {
    expect(hasDepth(toc([0, "Часть", 0], [1, "Глава", 4]))).toBe(true);
  });

  it("пустое оглавление ничего не сворачивает", () => {
    expect(hasDepth([])).toBe(false);
  });
});

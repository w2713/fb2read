/**
 * Решения обмена, которые проверяются без сервера.
 *
 * Сам обмен проверяется настоящим сервером в настоящем браузере — здесь
 * только то, что можно спросить у чистых функций: как читаются настройки и
 * что считать изменением.
 */

import { bookTimeout, type SyncState } from "@fb2read/core";
import { describe, expect, it } from "vitest";
import {
  FETCH_BUDGET,
  TALK_TIMEOUT,
  budget,
  changed,
  guessDevice,
  syncSettings,
  tell,
} from "../src/sync.js";

const state = (block: number, bookmarks: SyncState["bookmarks"] = []): SyncState => ({
  hash: "a".repeat(64),
  block,
  total: 100,
  title: "Книга",
  author: "Автор",
  at: 1000,
  bookmarks,
});

describe("настройки обмена", () => {
  it("без адреса обмена нет вовсе", () => {
    // Это обычное состояние читалки, а не ошибка: сервер нужен не всем.
    expect(syncSettings({})).toBeNull();
    expect(syncSettings({ syncUrl: "   " })).toBeNull();
  });

  it("читаются полностью", () => {
    expect(
      syncSettings({
        syncUrl: " https://books.example.org ",
        syncToken: "секрет",
        device: "телефон",
        syncAuto: false,
      }),
    ).toEqual({
      url: "https://books.example.org",
      token: "секрет",
      device: "телефон",
      auto: false,
    });
  });

  it("обмен при закрытии книги включён, пока его не выключили", () => {
    expect(syncSettings({ syncUrl: "https://x" })!.auto).toBe(true);
  });

  it("устройство узнаётся по браузеру", () => {
    expect(guessDevice("Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X)")).toBe("iPhone");
    expect(guessDevice("Mozilla/5.0 (Linux; Android 14)")).toBe("Android");
    expect(guessDevice("что-то незнакомое")).toBe("браузер");
  });
});

describe("что считать изменением", () => {
  it("другое место — изменение", () => {
    expect(changed(state(10), state(40))).toBe(true);
  });

  it("снятая и поставленная закладка дают ту же длину, но это изменение", () => {
    // На эту удочку читалка в терминале однажды уже попалась: список сравнивали
    // по длине, и снятые закладки воскресали при каждом обмене.
    const было = state(10, [{ block: 5, at: 100 }]);
    const стало = state(10, [{ block: 5, at: 200, deleted: true }]);
    expect(changed(было, стало)).toBe(true);
  });

  it("то же самое изменением не считается", () => {
    const marks = [{ block: 5, at: 100 }];
    expect(changed(state(10, marks), state(10, [...marks]))).toBe(false);
  });
});

describe("жалоба сервера в итоге обмена", () => {
  it("идёт следом за итогом, а не вместо него", () => {
    // Обмен состоялся, и читателю важно и то, и другое: что приехало и что с
    // часами неладно.
    expect(tell({ sent: 1, updated: 2, warning: "часы устройства расходятся с сервером на 700 мин" })).toBe(
      "отправлено книг: 1, обновилось мест: 2; часы устройства расходятся с сервером на 700 мин",
    );
  });

  it("слышна и тогда, когда обмену нечего было делать", () => {
    expect(tell({ warning: "часы устройства расходятся" })).toBe(
      "всё и так совпадало; часы устройства расходятся",
    );
  });

  it("без жалобы итог прежний", () => {
    expect(tell({})).toBe("всё и так совпадало");
    expect(tell({ sent: 2 })).toBe("отправлено книг: 2");
  });
});

describe("удалённое с сервера в итоге обмена", () => {
  it("названо прямо: книга лежит на полке, а на сервер не уезжает", () => {
    // Молчание об этом читатель принял бы за поломку обмена.
    expect(tell({ refused: 1 })).toBe("удалённых с сервера не возвращали: 1");
    expect(tell({ sent: 1, refused: 2 })).toBe("отправлено книг: 1, удалённых с сервера не возвращали: 2");
  });

  it("когда возвращать было нечего, лишнего не говорит", () => {
    expect(tell({ sent: 1, refused: 0 })).toBe("отправлено книг: 1");
  });
});

describe("ждущие на сервере в итоге обмена", () => {
  it("названы вслух, чтобы облако на полке не выглядело поломкой", () => {
    expect(tell({ taken: 2, waiting: 3 })).toBe(
      "получено книг: 2, ждут на сервере: 3 — коснитесь, чтобы забрать",
    );
  });

  it("когда всё забрали, о ждущих молчит", () => {
    expect(tell({ taken: 2, waiting: 0 })).toBe("получено книг: 2");
  });
});

describe("сроки обмена", () => {
  it("у разговора срок свой и короткий: читатель смотрит на строку", () => {
    // Список, места и удаление — запросы короткие, ждать их минутами незачем.
    // А книге срок считается по размеру, и он всегда больше.
    expect(TALK_TIMEOUT).toBe(30_000);
    expect(bookTimeout(1)).toBeGreaterThan(TALK_TIMEOUT);
  });
});

describe("сколько забирать за один обмен", () => {
  const книга = (size: number, hash = "a") => ({ hash, size });

  it("берёт свежие книги, пока они укладываются в предел", () => {
    // Сервер отдаёт список новыми сверху — их и ждут на другом устройстве.
    const { take, waiting } = budget([книга(5e6, "1"), книга(5e6, "2"), книга(5e6, "3")]);
    expect(take.map((b) => b.hash)).toEqual(["1", "2", "3"]);
    expect(waiting).toBe(0);
  });

  it("не влезшую пропускает, а очередь идёт дальше", () => {
    // Иначе одна толстая книга в начале списка держала бы всю полку вечно:
    // каждый обмен упирался бы в неё, и мелкие книги не приезжали бы никогда.
    const мегабайт = 1024 * 1024;
    const { take, waiting } = budget([
      книга(15 * мегабайт, "1"),
      книга(10 * мегабайт, "2"),
      книга(1 * мегабайт, "3"),
    ]);
    expect(take.map((b) => b.hash)).toEqual(["1", "3"]);
    expect(waiting).toBe(1);
  });

  it("первую книгу берёт всегда, даже если она одна толще предела", () => {
    // Иначе такая книга не приехала бы никогда: в браузере за незнакомой
    // книгой сходить нечем — касание есть только у снятых с полки.
    const { take, waiting } = budget([книга(FETCH_BUDGET + 1, "толстая")]);
    expect(take.map((b) => b.hash)).toEqual(["толстая"]);
    expect(waiting).toBe(0);
  });

  it("обмен, в котором приехала толстая, других книг не тянет", () => {
    const мегабайт = 1024 * 1024;
    const { take, waiting } = budget([
      книга(30 * мегабайт, "толстая"),
      книга(1 * мегабайт, "мелкая"),
    ]);
    expect(take.map((b) => b.hash)).toEqual(["толстая"]);
    expect(waiting).toBe(1);
  });

  it("когда забирать нечего, не ждёт никто", () => {
    expect(budget([])).toEqual({ take: [], waiting: 0 });
  });
});

describe("итог обмена словами", () => {
  it("когда ничего не менялось, так и сказано", () => {
    expect(tell({})).toBe("всё и так совпадало");
  });

  it("перечисляет только то, что было", () => {
    expect(tell({ sent: 2, updated: 1 })).toBe("отправлено книг: 2, обновилось мест: 1");
    expect(tell({ taken: 3 })).toBe("получено книг: 3");
  });
});

/**
 * Арифметика разворота.
 *
 * Здесь основная тяжесть проверок: сам разворот — это несколько правил CSS, а
 * ошибиться можно в числах, и каждая такая ошибка видна читателю сразу —
 * пропущенной строкой, уехавшей страницей или разворотом там, где его быть не
 * должно.
 */

import { describe, expect, it } from "vitest";
import { searchTop } from "../src/position.js";
import { fitsSpread, pageAt, pageCount, pageLeft, pageStep, stepPage } from "../src/spread.js";

describe("порог разворота", () => {
  it("ноутбук и планшет в альбомной — разворот", () => {
    expect(fitsSpread(1440, 900, 16)).toBe(true);
    expect(fitsSpread(1133, 744, 16)).toBe(true);
  });

  it("iPhone в альбомной — не разворот, хотя окно широкое", () => {
    // 844 пикселя шире порога по ширине, и по одной ширине разворот бы
    // включился. Высота 390 — колонка в пять строк, читать такое нельзя.
    expect(fitsSpread(844, 390, 16)).toBe(false);
    // Ширины ему хватает: значит, отсеяла именно высота, а не она.
    expect(fitsSpread(844, 900, 16)).toBe(true);
  });

  it("телефон в книжной — не разворот", () => {
    expect(fitsSpread(390, 844, 16)).toBe(false);
    expect(fitsSpread(375, 667, 16)).toBe(false);
  });

  it("узкое окно на столе — не разворот", () => {
    expect(fitsSpread(700, 900, 16)).toBe(false);
  });

  it("порог считается в рем, а не в пикселях", () => {
    // Читатель увеличил шрифт средствами системы: окно то же, а текста в него
    // влезает меньше, и колонки становятся уже разумного.
    expect(fitsSpread(900, 700, 16)).toBe(true);
    expect(fitsSpread(900, 700, 24)).toBe(false);
  });
});

describe("страницы разворота", () => {
  it("шаг — содержимое плюс промежуток, а не ширина окна", () => {
    // Ловушка разворота: следующая страница начинается за промежутком между
    // колонками. Листание по ширине содержимого уползало бы на него каждый раз.
    expect(pageStep(1248, 48)).toBe(1296);
  });

  it("смещение на границе страницы — уже следующая", () => {
    expect(pageAt(0, 1296)).toBe(0);
    expect(pageAt(1200, 1296)).toBe(0);
    expect(pageAt(1296, 1296)).toBe(1);
    expect(pageAt(2592, 1296)).toBe(2);
  });

  it("дробные колонки не сбивают номер страницы", () => {
    // Ширины колонок дробные, и левый край колонки измеряется то в 1296, то в
    // 1295.6. Без допуска второй случай считался бы прошлой страницей — и
    // абзац, к которому перешли, остался бы за правым краем окна.
    expect(pageAt(1295.6, 1296)).toBe(1);
  });

  it("страница не уходит левее начала книги", () => {
    expect(pageAt(-40, 1296)).toBe(0);
  });

  it("начало страницы считается тем же шагом", () => {
    expect(pageLeft(3, 1296)).toBe(3888);
  });

  it("неполная последняя страница всё равно страница", () => {
    expect(pageCount(1296, 1296)).toBe(1);
    expect(pageCount(1300, 1296)).toBe(2);
  });

  it("страница есть даже у пустой книги", () => {
    expect(pageCount(0, 1296)).toBe(1);
  });

  it("листание не уходит за края книги", () => {
    expect(stepPage(0, -1, 5)).toBe(0);
    expect(stepPage(4, 1, 5)).toBe(4);
    expect(stepPage(2, 1, 5)).toBe(3);
  });
});

describe("какой абзац читают в развороте", () => {
  /**
   * Тот же двоичный поиск, что и при прокрутке, — меняется только мерка: вместо
   * «верх абзаца минус край окна» берётся «начало абзаца минус левый край
   * страницы».
   */
  function абзацСтраницы(начала: number[], страница: number): number | null {
    return searchTop(начала.length, (i) => начала[i]! - страница);
  }

  it("абзац, начавшийся на прошлой странице, — тот, который читают", () => {
    // Он занимает верх левой колонки, а следующий начинается ниже. Взять
    // следующий значило бы увести место вперёд через полстраницы текста.
    expect(абзацСтраницы([0, 40, 90, 140, 190], 100)).toBe(2);
  });

  it("абзац ровно с начала страницы — он и есть", () => {
    expect(абзацСтраницы([0, 50, 100, 150], 100)).toBe(2);
  });

  it("на первой странице — первый абзац", () => {
    expect(абзацСтраницы([0, 50, 100, 150], 0)).toBe(0);
  });
});

/**
 * Переносы по-русски.
 *
 * Проверяются обязательные школьные правила: часть без гласной, одинокая
 * буква, `ь`/`ъ`/`й` в начале переноса и согласная, оторванная от своей
 * гласной. Каждое из них, нарушенное, читатель замечает сразу.
 */

import { describe, expect, it } from "vitest";
import { hyphenAt, hyphenPoints } from "../src/hyphen.js";
import { strWidth } from "../src/width.js";

/** Слово с расставленными переносами: так их видно глазами. */
function показать(word: string): string {
  const места = hyphenPoints(word);
  let out = "";
  let было = 0;
  for (const at of места) {
    out += word.slice(было, at) + "-";
    было = at;
  }
  return out + word.slice(было);
}

describe("переносы", () => {
  it("делят слово по слогам", () => {
    expect(показать("молоко")).toBe("мо-ло-ко");
  });

  it("не отрывают согласную от гласной за ней", () => {
    // «люб-овь» — грубая ошибка, заметная любому читателю.
    expect(показать("любовь")).toBe("лю-бовь");
  });

  it("не начинают перенос с ь, ъ или й", () => {
    // «во-йна» и «бол-ьшой» — так не переносят: эти буквы держатся за
    // предыдущую. Проверяется само правило, а не единственное деление: у
    // слова бывает несколько допустимых, и требовать одно значило бы
    // проверять мой вкус, а не правило.
    expect(показать("война")).toBe("вой-на");
    expect(hyphenPoints("большой")).not.toContain(3);
    expect(hyphenPoints("подъезд")).not.toContain(3);
    // А после них переносить можно, и «подъ-езд» разрешено.
    expect(hyphenPoints("подъезд")).toContain(4);
  });

  it("оставляют гласную в каждой части", () => {
    // «аи-ст» оставило бы хвост без гласной, а «ст» не прочесть.
    expect(hyphenPoints("аист")).toEqual([]);
  });

  it("не отрывают одну букву и не переносят одну", () => {
    expect(hyphenPoints("яма")).toEqual([]);
    expect(hyphenPoints("оса")).toEqual([]);
  });

  it("короткие слова не переносятся вовсе", () => {
    for (const word of ["и", "на", "дом", "小"]) expect(hyphenPoints(word)).toEqual([]);
  });

  it("латиницу не трогают: у неё свои правила", () => {
    // Отдельной проверки на кириллицу нет: гласными считаются только русские
    // буквы, и латинское слово отсеивается правилом о гласной в каждой части.
    expect(hyphenPoints("computer")).toEqual([]);
    expect(hyphenPoints("hyphenation")).toEqual([]);
  });

  it("знаки препинания вокруг слова не мешают", () => {
    // Слово приходит из текста вместе с точкой или кавычкой.
    expect(показать("молоко.")).toBe("мо-ло-ко.");
    expect(показать("«молоко»")).toBe("«мо-ло-ко»");
  });

  it("выбирают самое дальнее место, которое влезает", () => {
    // Чем больше начала осталось на строке, тем меньше растягивать промежутки.
    expect(hyphenAt("молоко", 20, strWidth)).toBe(4);
    expect(hyphenAt("молоко", 3, strWidth)).toBe(2);
  });

  it("когда места нет, переносить отказываются", () => {
    expect(hyphenAt("молоко", 2, strWidth)).toBe(0);
    expect(hyphenAt("аист", 20, strWidth)).toBe(0);
  });

  it("дефис считается в ширину, а не забывается", () => {
    // Без него перенос вылезал бы за край колонки ровно на один знак.
    const at = hyphenAt("молоко", 3, strWidth);
    expect(strWidth("молоко".slice(0, at)) + 1).toBeLessThanOrEqual(3);
  });
});

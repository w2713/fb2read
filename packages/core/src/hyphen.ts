/**
 * Расстановка переносов по-русски — правилами, без словаря.
 *
 * Словаря не будет намеренно: в этом репозитории своими руками написаны и
 * распаковщик zip, и base64, и sha256, а рантайм-зависимость ровно одна.
 * Таблицы переносов стали бы самой большой частью читалки, а выгода от них
 * для чтения в терминале невелика.
 *
 * Правила школьные и все обязательные:
 *
 *  1. в каждой части должна остаться гласная — «аист» не переносится вовсе;
 *  2. одну букву не отрывают и не переносят;
 *  3. `ь`, `ъ` не отрывают от согласной перед ними, `й` — от гласной: значит,
 *     перенос перед ними запрещён, а после них разрешён («подъ-езд», «вой-на»);
 *  4. согласную не отрывают от гласной за ней — «лю-бовь», а не «люб-овь».
 *
 * Чего эти правила не знают — состава слова и границ слогов. Они дадут
 * допустимый перенос, но не всегда тот, что в словаре: рядом с верным
 * «подъ-езд» предложат «по-дъезд», рядом с «боль-шой» — «бо-льшой». Ни одна
 * из этих частей не становится нечитаемой, но словарь выбрал бы другое.
 * Обещать словарное качество нечестно, и я не буду.
 *
 * Латиница не переносится, и отдельной проверки на это не нужно: гласными
 * считаются только русские буквы, а без гласной в обеих частях перенос не
 * ставится. Проверка на кириллицу тут была и оказалась мёртвой — убрать её не
 * заметила ни одна проверка.
 */

const ГЛАСНЫЕ = new Set("аеёиоуыэюя");
const ЗНАКИ = new Set("ьъй");

function гласная(ch: string | undefined): boolean {
  return ch !== undefined && ГЛАСНЫЕ.has(ch.toLowerCase());
}

function согласная(ch: string | undefined): boolean {
  return ch !== undefined && !гласная(ch) && !ЗНАКИ.has(ch.toLowerCase());
}

/** Есть ли в куске хоть одна гласная: без неё часть слова не читается. */
function сГласной(part: string): boolean {
  for (const ch of part) if (гласная(ch)) return true;
  return false;
}

/**
 * Места, где слово можно разорвать.
 *
 * Возвращает смещения: перенос ставится перед символом с этим номером, то есть
 * `слово.slice(0, at) + "-"` остаётся на строке, а `слово.slice(at)` уходит на
 * следующую. Порядок — от начала слова к концу.
 *
 * Знаки препинания вокруг слова не мешают: «моло-ко.» разрешено, а «молоко-.»
 * отсеется само — в хвосте не останется гласной.
 */
export function hyphenPoints(word: string): number[] {
  const out: number[] = [];
  // Две буквы с каждой стороны: одну не отрывают и не переносят.
  for (let at = 2; at <= word.length - 2; at += 1) {
    const до = word[at - 1];
    const после = word[at];
    // Перенос перед `ь`, `ъ`, `й` запретён: они держатся за предыдущую букву.
    if (ЗНАКИ.has(после!.toLowerCase())) continue;
    // Согласную не отрывают от гласной за ней.
    if (согласная(до) && гласная(после)) continue;
    if (!сГласной(word.slice(0, at)) || !сГласной(word.slice(at))) continue;
    out.push(at);
  }
  return out;
}

/**
 * Самое дальнее место разрыва, при котором начало слова умещается в ширину.
 *
 * Ширину занимает и сам дефис, поэтому запас считается с ним. Пусто — значит,
 * переносить некуда: слово короткое, места нет или правила не дали ни одного
 * разрыва.
 */
export function hyphenAt(word: string, room: number, width: (text: string) => number): number {
  const места = hyphenPoints(word);
  for (let i = места.length - 1; i >= 0; i -= 1) {
    const at = места[i]!;
    if (width(word.slice(0, at)) + width("-") <= room) return at;
  }
  return 0;
}

/**
 * Поиск по всей библиотеке: пределы, порядок и слова о ходе дела.
 *
 * Поиск внутри одной книги считает `search.ts`, он же собирает выдержки вокруг
 * совпадений. Здесь только то, что решается про библиотеку целиком: с какой
 * книги начинать, сколько находок показывать из одной книги и что писать
 * читателю, пока идёт перебор.
 *
 * Правила общие для обеих читалок: в браузере это полка, в терминале — список
 * книг, и отвечать они должны одинаково.
 *
 * Почему перебор, а не указатель. Измерено на книге в 2.3 МБ: разбор 408 мс,
 * сам поиск по разобранной книге 93 мс. Вся цена — в разборе, и указатель
 * (сохранённый текст всех книг) снял бы её ценой второй копии библиотеки. В
 * браузере платить за это местом тем более не стоит: он и так вправе стереть
 * хранилище сайта, куда давно не заходили. Вместо этого находки показываются
 * по мере готовности, книга за книгой, и первая появляется через полсекунды.
 */



/**
 * Короче этого не ищем.
 *
 * По одной букве совпадёт всё подряд, а стоить это будет полного перебора
 * библиотеки: читатель заплатит секундами за список, в котором нет ответа.
 */
export const MIN_QUERY = 2;

/** Сколько находок показывать из одной книги. */
export const PER_BOOK = 20;

/** Стоит ли вообще искать это. */
export function worthFinding(query: string): boolean {
  return query.trim().length >= MIN_QUERY;
}

/**
 * В каком порядке обходить книги.
 *
 * Недавно читанные первыми: ищут обычно в том, что читают, и ждать перебора
 * всей библиотеки ради книги, закрытой полчаса назад, незачем. Список и так
 * отсортирован по времени, так что порядок здесь только закрепляется — но
 * закрепляется нарочно: от него зависит, через сколько читатель увидит первую
 * находку.
 *
 * Книга описана здесь одним лишь временем: что ещё в ней есть — дело того, кто
 * ищет. В браузере это строка полки, в терминале — строка списка книг.
 */
export function findOrder<T extends { at: number }>(entries: readonly T[]): T[] {
  return [...entries].sort((a, b) => b.at - a.at);
}

/** Находки одной книги: показанные и сколько ещё осталось за пределом. */
export interface Capped<T> {
  shown: T[];
  more: number;
}

/**
 * Обрезает список находок.
 *
 * Книга, где искомое слово на каждой странице, выдала бы тысячи строк, и
 * список перестал бы читаться. Показываем начало и честно говорим, сколько
 * осталось.
 */
export function capHits<T>(hits: readonly T[], limit = PER_BOOK): Capped<T> {
  return { shown: hits.slice(0, limit), more: Math.max(hits.length - limit, 0) };
}

/**
 * Что написать, пока идёт перебор.
 *
 * Число просмотренных книг важнее числа находок: по нему видно, что работа
 * идёт и сколько её осталось. Когда всё просмотрено, счёт книг уже не нужен —
 * нужен ответ.
 */
export function progressLine(done: number, total: number, found: number): string {
  const итог = found ? `нашлось ${found}` : "ничего не нашлось";
  if (done >= total) return итог;
  return `просмотрено ${done} из ${total} · ${found ? `нашлось ${found}` : "пока пусто"}`;
}
